#!/bin/bash -e
# RAUC client config + public keyring. Fails closed without a real keyring unless this is a dev build.
: "${PM_SRC:?}"
R="${ROOTFS_DIR}"; O="$PM_SRC/os"
install -d "$R/etc/rauc"
install -m 644 "$O/rauc/system.conf" "$R/etc/rauc/system.conf"
install -m 755 "$O/rauc/rauc-tryboot-backend" "$R/usr/lib/pocketmate/rauc-tryboot-backend"
if [ -f "$O/keys/public/keyring.pem" ]; then
    install -m 644 "$O/keys/public/keyring.pem" "$R/etc/rauc/keyring.pem"
elif [ "${PM_DEV_KEYRING:-0}" = 1 ]; then
    echo "WARNING: dev image without a release keyring: RAUC installs will fail until one is added" >&2
else
    echo "os/keys/public/keyring.pem missing (no keys are generated by this repo; see os/keys/README.md)" >&2
    exit 1
fi
