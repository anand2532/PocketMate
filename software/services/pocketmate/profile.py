"""pm-profile (§6.11): SKU detection + model manifest verification -> /run/pm/profile.toml."""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

REQUIRED = {"cm5-4g": ("asr", "llm", "tts_en", "tts_hi"), "cm5-2g": ("asr", "llm"), "cm4": ("asr", "llm")}
SUPPORTED_V1 = {"cm5-4g"}


@dataclass
class Profile:
    sku: str
    model: str
    mem_total_kb: int
    serial: str | None
    supported: bool
    models: dict[str, dict] = field(default_factory=dict)
    missing: list[str] = field(default_factory=list)


def _read(p: Path) -> str | None:
    try:
        return p.read_bytes().rstrip(b"\x00\n").decode(errors="replace")
    except OSError:
        return None


def detect(root: str | Path = "/") -> tuple[str, str, int, str | None]:
    r = Path(root)
    model = _read(r / "proc/device-tree/model") or "unknown"
    serial = _read(r / "proc/device-tree/serial-number")
    mem = 0
    for line in (_read(r / "proc/meminfo") or "").splitlines():
        if line.startswith("MemTotal:"):
            mem = int(line.split()[1])
    if "Compute Module 5" in model:
        sku = "cm5-2g" if mem < 2_500_000 else "cm5-4g"
    elif "Compute Module 4" in model:
        sku = "cm4"
    else:
        sku = "unknown"
    return sku, model, mem, serial


def verify_models(manifest: Path, sku: str, *, hash_files: bool = True) -> tuple[dict[str, dict], list[str]]:
    """manifest.json: {"models":[{"role","file","sha256","ram_mb","skus":[...]}]} (format [impl], VERIFY with
    the models-bundle build)."""
    ok: dict[str, dict] = {}
    try:
        data = json.loads(manifest.read_text())
    except (OSError, ValueError):
        return ok, list(REQUIRED.get(sku, ()))
    for m in data.get("models", []):
        if sku not in m.get("skus", [sku]):
            continue
        f = manifest.parent / m["file"]
        if not f.is_file():
            continue
        if hash_files:
            h = hashlib.sha256()
            with f.open("rb") as fh:
                for b in iter(lambda: fh.read(1 << 20), b""):
                    h.update(b)
            if h.hexdigest() != m.get("sha256"):
                continue
        ok[m["role"]] = m
    return ok, [r for r in REQUIRED.get(sku, ()) if r not in ok]


def build(root: str | Path = "/", manifest: str | Path = "/opt/pm/models/manifest.json",
          allow_unsupported: bool = False) -> Profile:
    sku, model, mem, serial = detect(root)
    models, missing = verify_models(Path(manifest), sku)
    return Profile(sku, model, mem, serial, sku in SUPPORTED_V1 or allow_unsupported, models, missing)


def to_toml(p: Profile) -> str:
    lines = ["# generated by pm-profile; do not edit", "[profile]", f'sku = "{p.sku}"',
             f'model = "{p.model}"', f"mem_total_kb = {p.mem_total_kb}",
             f"supported = {'true' if p.supported else 'false'}",
             "missing = [" + ", ".join(f'"{m}"' for m in p.missing) + "]", "[models]"]
    lines += [f'{role} = "{m["file"]}"' for role, m in sorted(p.models.items())]
    return "\n".join(lines) + "\n"
