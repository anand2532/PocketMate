"""Generate firmware/include/pm_proto_gen.h and firmware/test/pm_proto_vectors.h from messages.py.

    python -m pocketmate.mcu.gen_c_header --out-dir ../firmware        # write
    python -m pocketmate.mcu.gen_c_header --out-dir ../firmware --check  # CI: fail if stale
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

from .crc import crc16_ccitt
from .frame import Frame
from .messages import (
    ACK_TIMEOUT_S,
    BAUD,
    MAX_PAYLOAD,
    MAX_RETRIES,
    MESSAGES,
    PROTO_VER,
    BootReason,
    ButtonAction,
    ButtonId,
    LightCase,
    MicMode,
    MicRailReason,
    PowerState,
    Status,
    ThermalStage,
    msg,
)

_CTYPE = {"B": "uint8_t", "b": "int8_t", "H": "uint16_t", "h": "int16_t", "I": "uint32_t", "i": "int32_t"}

# Fixed vectors shared by the Python and C test suites.
VECTORS = [
    ("HELLO", 1, msg("HELLO", proto_ver=PROTO_VER, cm5_fw_ver=0x000400)),
    ("MIC_ENABLE", 7, msg("MIC_ENABLE", on=1, session_id=0x1234, mode=0, max_s=120)),
    ("ACK", 7, msg("ACK", acked_seq=7, status=int(Status.MUTED))),
    ("EVT_BUTTON", 0x81, msg("EVT_BUTTON", id=1, action=0, t_ms=123456, woke=1)),
    ("EVT_THERMAL", 0x82, msg("EVT_THERMAL", case_ntc_dC=412, cell_dC=-55, ambient_dC_est=350,
                              stage=2, adc_fault=0, lux=3)),
    ("EVT_MIC_RAIL", 0x83, msg("EVT_MIC_RAIL", on=0, reason=int(MicRailReason.MUTE), session_id=0x1234)),
    ("SET_CHARGE_CFG", 9, msg("SET_CHARGE_CFG", ntc_r25=10000, beta=3435, rt1=5210, rt2=29870,
                               cold_off_dC=100, cold_on_dC=120, hot_on_dC=380, hot_off_dC=400,
                               derate_dC=350, beta_measured=0)),
    ("HEARTBEAT_ZERO", 0, msg("HEARTBEAT", uptime_s=0, cm5_state=0)),  # payload of zeros: COBS stress
]


def _enum(name: str, e) -> str:
    lines = ["typedef enum {"]
    for m in e:
        lines.append(f"    {name.upper()}_{m.name} = {int(m.value)},")
    lines.append(f"}} pm_{name}_t;\n")
    return "\n".join(lines)


# Python field names that are C keywords get a C-only name (wire layout is unchanged).
_C_RENAME = {"case": "light_case"}


def header() -> str:
    out = [
        "/* AUTO-GENERATED by services/pocketmate/mcu/gen_c_header.py -- DO NOT EDIT. */",
        "#ifndef PM_PROTO_GEN_H", "#define PM_PROTO_GEN_H", "#include <stdint.h>", "",
        f"#define PM_PROTO_VER {PROTO_VER}u",
        f"#define PM_MAX_PAYLOAD {MAX_PAYLOAD}u",
        f"#define PM_BAUD {BAUD}u",
        f"#define PM_ACK_TIMEOUT_MS {int(ACK_TIMEOUT_S * 1000)}u",
        f"#define PM_MAX_RETRIES {MAX_RETRIES}u",
        f"#define PM_CRC_CHECK_123456789 0x{crc16_ccitt(b'123456789'):04X}u", "",
    ]
    for m in MESSAGES:
        out.append(f"#define PM_MSG_{m.name} 0x{m.type_id:02X}u")
        out.append(f"#define PM_LEN_{m.name} {m.fixed_len}u{'  /* + variable tail */' if m.var_tail else ''}")
    out.append("")
    for e, n in ((Status, "status"), (PowerState, "pstate"), (MicMode, "micmode"), (ButtonId, "btn"),
                 (ButtonAction, "btnact"), (MicRailReason, "railreason"), (BootReason, "boot"),
                 (ThermalStage, "tstage"), (LightCase, "lcase")):
        out.append(_enum(n, e))
    # packed payload structs (little-endian target; host tests run on LE x86)
    for m in MESSAGES:
        if not m.fields:
            continue
        out.append("typedef struct __attribute__((packed)) {")
        for f, c in zip(m.fields, m.fmt, strict=True):
            out.append(f"    {_CTYPE[c]} {_C_RENAME.get(f, f)};")
        out.append(f"}} pm_{m.name.lower()}_t;")
        out.append(f"_Static_assert(sizeof(pm_{m.name.lower()}_t) == {m.fixed_len}, \"{m.name} size\");")
    out += ["", "#endif /* PM_PROTO_GEN_H */", ""]
    return "\n".join(out)


def vectors() -> str:
    out = ["/* AUTO-GENERATED by gen_c_header.py -- DO NOT EDIT. Cross-language frame vectors. */",
           "#ifndef PM_PROTO_VECTORS_H", "#define PM_PROTO_VECTORS_H", "#include <stdint.h>", "",
           "typedef struct { const char *name; uint8_t type; uint8_t seq; uint8_t payload_len;",
           "                 const uint8_t *payload; uint8_t wire_len; const uint8_t *wire; } pm_vector_t;", ""]
    names = []
    for i, (name, seq, m) in enumerate(VECTORS):
        f = Frame.from_message(m, seq)
        wire = f.encode()
        pl = f.payload
        out.append(f"static const uint8_t v{i}_payload[] = {{{', '.join(f'0x{b:02X}' for b in pl) or '0'}}};")
        out.append(f"static const uint8_t v{i}_wire[] = {{{', '.join(f'0x{b:02X}' for b in wire)}}};")
        names.append(f'    {{"{name}", 0x{f.type_id:02X}, {seq}, {len(pl)}, v{i}_payload, {len(wire)}, v{i}_wire}},')
    out.append("static const pm_vector_t pm_vectors[] = {")
    out += names
    out += ["};", f"#define PM_N_VECTORS {len(VECTORS)}u", "", "#endif", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", required=True, help="firmware/ directory")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    root = Path(a.out_dir)
    targets = {root / "include" / "pm_proto_gen.h": header(), root / "test" / "pm_proto_vectors.h": vectors()}
    stale = []
    for p, text in targets.items():
        if a.check:
            if not p.exists() or p.read_text() != text:
                stale.append(str(p))
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    if stale:
        print("stale generated files:", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

_ = struct  # keep import for readers extending vectors
